from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, SecretStr
from sqlalchemy.engine import URL, make_url


class StrictSettingsModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class GerritRestAuth(StrictSettingsModel):
    mode: Literal["none", "basic", "bearer"] = "none"
    username: str | None = None
    password_env: str | None = None
    token_env: str | None = None

    def secret(self) -> str | None:
        env_name = self.password_env if self.mode == "basic" else self.token_env
        return os.environ.get(env_name) if env_name else None


class GerritSettings(StrictSettingsModel):
    ssh_host: str
    ssh_port: int = Field(default=29418, ge=1, le=65535)
    ssh_user: str
    ssh_key_path: Path
    known_hosts_path: Path | None = None
    strict_host_key_checking: bool = True
    rest_url: str
    rest_auth: GerritRestAuth = Field(default_factory=GerritRestAuth)
    # Optional bootstrap allowlist. The Admin Web can start from an empty list and persist projects.
    projects: list[str] = Field(default_factory=list)
    event_reconnect_min_seconds: float = Field(default=1.0, gt=0)
    event_reconnect_max_seconds: float = Field(default=60.0, gt=0)
    request_timeout_seconds: float = Field(default=20.0, gt=0)
    ca_bundle_path: Path | None = None
    review_tag: str = "autogenerated:pe-ai-review"
    notify: Literal["NONE", "OWNER", "OWNER_REVIEWERS", "ALL"] = "OWNER"
    # Gerrit 3.8 change.commentSizeLimit defaults to 16 KiB. Keep individual change/inline
    # messages below the configured server ceiling so one verbose model finding cannot reject the
    # whole Set Review request.
    max_comment_bytes: int = Field(default=16 * 1024, ge=1024, le=3 * 1024 * 1024)


