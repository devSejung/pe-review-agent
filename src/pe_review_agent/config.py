class DatabaseSettings(StrictSettingsModel):
    dsn: str | None = None
    host: str = "postgres"
    port: int = Field(default=5432, ge=1, le=65535)
    username: str = "pe_review"
    database: str = "pe_review"
    password_env: str = "POSTGRES_PASSWORD"
    pool_size: int = Field(default=5, ge=1, le=100)
    max_overflow: int = Field(default=5, ge=0, le=100)

    def connection_url(self) -> URL:
        if self.dsn:
            return make_url(self.dsn)
        password = os.environ.get(self.password_env)
        if password is None:
            raise ValueError(
                f"database password environment variable {self.password_env!r} is not set"
            )
        return URL.create(
            "postgresql+asyncpg",
            username=self.username,
            password=password,
            host=self.host,
            port=self.port,
            database=self.database,
        )


