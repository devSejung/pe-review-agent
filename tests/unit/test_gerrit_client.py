@pytest.mark.asyncio
async def test_reconciliation_query_paginates_recent_open_allowlisted_changes() -> None:
    starts: list[str] = []
    queries: list[str] = []

    def handler(request: httpx.Request) -> httpx.Response:
        starts.append(request.url.params["S"])
        queries.append(request.url.params["q"])
        if request.url.params["S"] == "0":
            return _gerrit_json([_change_info(number=123, more=True)])
        return _gerrit_json([_change_info(number=124, revision=NEW_REVISION, patchset=2)])

    async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as http_client:
        client = GerritRestClient(_settings(), client=http_client)
        events = await client.reconciliation_events(
            since=datetime(2026, 9, 16, 5, 30, tzinfo=UTC),
            page_size=1,
        )

    assert starts == ["0", "1"]
    assert all('project:"team/fw"' in query for query in queries)
    assert all('after:"2026-09-16 05:30:00 +0000"' in query for query in queries)
    identities = [(event.change_number, event.patchset_number) for event in events]
    assert identities == [(123, 4), (124, 2)]
    assert events[0].uploader == "alice"
    assert events[0].raw["type"] == "reconciliation"


