REVISION = "a" * 40
NEW_REVISION = "b" * 40


def _settings(
    *,
    auth: GerritRestAuth | None = None,
    projects: list[str] | None = None,
) -> GerritSettings:
    return GerritSettings(
        ssh_host="gerrit.internal",
        ssh_user="review-bot",
        ssh_key_path=Path("/run/secrets/gerrit_key"),
        rest_url="https://gerrit.internal/gerrit",
        rest_auth=auth or GerritRestAuth(mode="none"),
        projects=projects or ["team/fw"],
        review_tag="autogenerated:pe-ai-review",
        notify="OWNER_REVIEWERS",
    )


def _change_info(
    *,
    project: str = "team/fw",
    number: int = 123,
    revision: str = REVISION,
    patchset: int = 4,
    more: bool = False,
) -> dict[str, object]:
    payload: dict[str, object] = {
        "id": f"{project}~main~Ideadbeef",
        "project": project,
        "branch": "main",
        "change_id": "Ideadbeef",
        "subject": "Fix memory ordering",
        "status": "NEW",
        "updated": "2026-09-16 06:00:00.000000000",
        "_number": number,
        "current_revision": revision,
        "revisions": {
            revision: {
                "_number": patchset,
                "ref": f"refs/changes/{number % 100:02d}/{number}/{patchset}",
                "uploader": {"username": "alice"},
            }
        },
    }
    if more:
        payload["_more_changes"] = True
    return payload


def _gerrit_json(payload: object, *, status_code: int = 200, **headers: str) -> httpx.Response:
    body = ")]}'\n" + json.dumps(payload)
    return httpx.Response(status_code, text=body, headers=headers)


@pytest.mark.asyncio
async def test_get_change_handles_xssi_prefix_and_context_path() -> None:
    seen: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        seen.append(request)
        return _gerrit_json(_change_info())

    async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as http_client:
        client = GerritRestClient(_settings(), client=http_client)
        change = await client.get_change("team/fw", 123)

    assert change.current_revision == REVISION
    assert change.patchset_number == 4
    assert change.ref == "refs/changes/23/123/4"
    assert seen[0].url.raw_path.decode().split("?", 1)[0] == (
        "/gerrit/changes/team%2Ffw~123/detail"
    )
    assert seen[0].url.params.get_list("o") == ["CURRENT_REVISION"]


