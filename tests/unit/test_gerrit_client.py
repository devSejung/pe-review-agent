@pytest.mark.asyncio
async def test_publish_review_builds_summary_inline_and_range_comments() -> None:
    requests: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        requests.append(request)
        if request.method == "GET":
            return _gerrit_json(_change_info())
        return _gerrit_json({"labels": {}})

    review = ReviewResult(
        summary="Found two firmware correctness issues.",
        findings=[
            Finding(
                severity=Severity.P1,
                category="bounds",
                title="Unchecked descriptor index",
                message="The descriptor index can exceed the ring size.",
                impact="Out-of-bounds MMIO access.",
                evidence="idx is incremented without modulo reduction.",
                remediation="Mask or reduce idx before dereference.",
                location=FindingLocation(path="drivers/dma.c", start_line=88),
            ),
            Finding(
                severity=Severity.P2,
                category="locking",
                title="Lock scope misses update",
                message="The status update occurs after releasing the lock.",
                impact="A reader can observe stale state.",
                evidence="unlock precedes status assignment.",
                location=FindingLocation(
                    path="drivers/dma.c",
                    start_line=120,
                    start_character=4,
                    end_line=122,
                    end_character=9,
                ),
            ),
        ],
    )

    async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as http_client:
        client = GerritRestClient(_settings(), client=http_client)
        await client.publish_review(
            project="team/fw",
            change_number=123,
            revision_sha=REVISION,
            review=review,
        )

    assert [request.method for request in requests] == ["GET", "POST"]
    payload = json.loads(requests[1].content)
    assert payload["message"] == "Found two firmware correctness issues."
    assert payload["tag"] == "autogenerated:pe-ai-review"
    assert payload["notify"] == "OWNER_REVIEWERS"
    assert payload["omit_duplicate_comments"] is True
    assert "labels" not in payload
    line_comment, range_comment = payload["comments"]["drivers/dma.c"]
    assert line_comment["line"] == 88
    assert "[P1] Unchecked descriptor index" in line_comment["message"]
    assert range_comment["range"] == {
        "start_line": 120,
        "start_character": 4,
        "end_line": 122,
        "end_character": 9,
    }
    assert "line" not in range_comment


