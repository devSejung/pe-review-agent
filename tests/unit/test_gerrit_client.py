def _settings(
    *,
    auth: GerritRestAuth | None = None,
    projects: list[str] | None = None,
) -> GerritSettings:
    return GerritSettings(
        ssh_host="gerrit.internal",
        ssh_user="review-bot",
        ssh_key_path=Path("/run/secrets/gerrit_key"),
        rest_url="https://gerrit.internal/gerrit",
        rest_auth=auth or GerritRestAuth(mode="none"),
        projects=projects or ["team/fw"],
        review_tag="autogenerated:pe-ai-review",
        notify="OWNER_REVIEWERS",
    )


def _change_info(
    *,
    project: str = "team/fw",
    number: int = 123,
    revision: str = REVISION,
    patchset: int = 4,
    more: bool = False,
    updated: str = "2026-09-16 06:00:00.000000000",
    created: str | None = None,
    status: str = "NEW",
) -> dict[str, object]:
    payload: dict[str, object] = {
        "id": f"{project}~main~Ideadbeef",
        "project": project,
        "branch": "main",
        "change_id": "Ideadbeef",
        "subject": "Fix memory ordering",
        "status": status,
        "updated": updated,
        "_number": number,
        "current_revision": revision,
        "revisions": {
            revision: {
                "_number": patchset,
                "ref": f"refs/changes/{number % 100:02d}/{number}/{patchset}",
                "uploader": {"username": "alice"},
                "created": created or updated,
                "commit": {"message": "Fix memory ordering\n\nAvoid stale reads."},
            }
        },
    }
    if more:
        payload["_more_changes"] = True
    return payload


def _gerrit_json(payload: object, *, status_code: int = 200, **headers: str) -> httpx.Response:
    body = ")]}'\n" + json.dumps(payload)
    return httpx.Response(status_code, text=body, headers=headers)


