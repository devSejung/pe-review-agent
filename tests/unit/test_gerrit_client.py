@pytest.mark.asyncio
async def test_rest_errors_are_classified_for_retry() -> None:
    responses = iter(
        [
            httpx.Response(429, headers={"Retry-After": "7"}),
            httpx.Response(503),
            httpx.Response(403),
            httpx.Response(404),
        ]
    )

    def handler(_: httpx.Request) -> httpx.Response:
        return next(responses)

    async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as http_client:
        client = GerritRestClient(_settings(), client=http_client)

        with pytest.raises(TransientError) as throttled:
            await client.get_change("team/fw", 123)
        assert throttled.value.retry_after_seconds == 7.0

        with pytest.raises(TransientError):
            await client.get_change("team/fw", 123)
        with pytest.raises(PermanentError):
            await client.get_change("team/fw", 123)
        with pytest.raises(PermanentError):
            await client.get_change("team/fw", 123)


