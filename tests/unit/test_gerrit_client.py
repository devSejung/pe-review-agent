@pytest.mark.asyncio
async def test_get_revision_commit_uses_requested_revision() -> None:
    seen_paths: list[str] = []

    def handler(request: httpx.Request) -> httpx.Response:
        seen_paths.append(request.url.path)
        return _gerrit_json({"commit": REVISION, "subject": "Fix memory ordering"})

    async with httpx.AsyncClient(transport=httpx.MockTransport(handler)) as http_client:
        client = GerritRestClient(_settings(), client=http_client)
        commit = await client.get_revision_commit("team/fw", 123, REVISION)

    assert commit["commit"] == REVISION
    assert seen_paths == [f"/gerrit/changes/team/fw~123/revisions/{REVISION}/commit"]
